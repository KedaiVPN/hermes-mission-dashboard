import { useState } from 'react';
import { useQuery, useMutation } from '@tanstack/react-query';
import { api } from '../lib/api';
import type { Task, QAPair } from '../types';

interface PlanningQAFormProps {
  task: Task;
  onGenerateSuccess: (taskId: number) => void;
  isLoading?: boolean;
}

export function PlanningQAForm({ task, onGenerateSuccess, isLoading = false }: PlanningQAFormProps) {
  const [answers, setAnswers] = useState<Record<string, string>>({
    tech_stack: '',
    scope_boundaries: '',
    integration_targets: '',
    non_functional: '',
  });

  const questionsQuery = useQuery({
    queryKey: ['planning-questions', task.id],
    queryFn: () => api.getPlanningQuestions(task.id),
  });

  const generateMutation = useMutation({
    mutationFn: () => {
      const qaHistory: QAPair[] = (questionsQuery.data?.questions || []).map((q) => ({
        question: q.question,
        answer: answers[q.id] || '',
      }));
      return api.generatePRD(task.id, {
        title: `PRD: ${task.title}`,
        content: '', // Will be auto-generated by backend
        qa_history: qaHistory,
      });
    },
    onSuccess: () => {
      onGenerateSuccess(task.id);
    },
  });

  if (questionsQuery.isLoading) {
    return (
      <div className="space-y-4">
        <div className="h-10 bg-white/5 animate-pulse rounded" />
        <div className="h-24 bg-white/5 animate-pulse rounded" />
      </div>
    );
  }

  if (questionsQuery.isError) {
    return <p className="text-sm text-red-400">Gagal memuat pertanyaan. Coba refresh.</p>;
  }

  const questions = questionsQuery.data?.questions || [];

  return (
    <form
      onSubmit={(e) => {
        e.preventDefault();
        generateMutation.mutate();
      }}
      className="space-y-5 bg-white/5 border border-white/10 rounded-lg p-5"
    >
      <div>
        <h2 className="text-sm font-semibold text-zinc-100 mb-4">Technical Discovery Questions</h2>
        <p className="text-xs text-zinc-500 mb-4">
          Jawab pertanyaan di bawah untuk membantu Hermes membuat PRD yang tepat dan auto-assign profil yang sesuai.
        </p>
      </div>

      <div className="space-y-4">
        {questions.map((q) => (
          <div key={q.id}>
            <label htmlFor={`qa-${q.id}`} className="block text-xs font-medium text-zinc-400 mb-1.5">
              {q.question}
            </label>
            <textarea
              id={`qa-${q.id}`}
              value={answers[q.id] || ''}
              onChange={(e) => setAnswers(prev => ({ ...prev, [q.id]: e.target.value }))}
              placeholder={q.placeholder}
              className="w-full px-3 py-2 bg-white/5 border border-white/10 rounded text-sm text-zinc-200 placeholder-zinc-600 focus:outline-none focus:border-blue-500/50 min-h-[80px]"
            />
          </div>
        ))}
      </div>

      <div className="flex gap-2 pt-3">
        <button
          type="submit"
          disabled={generateMutation.isPending || isLoading}
          className="flex-1 px-3 py-2.5 bg-blue-500/15 border border-blue-500/30 rounded text-sm font-medium text-blue-300 hover:bg-blue-500/20 disabled:opacity-50 transition-colors"
        >
          {generateMutation.isPending ? 'Generating PRD…' : 'Generate PRD & Assign Profiles'}
        </button>
      </div>

      {generateMutation.isError && (
        <p className="text-xs text-red-400" role="alert">
          Gagal generate PRD. Coba lagi.
        </p>
      )}
    </form>
  );
}
